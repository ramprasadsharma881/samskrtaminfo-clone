                            </div>
                            <div class="pada">
                                पदविभागः- धर्मः अयं सहचारिण्याः जीवता अजीवता अपि वा । पत्या सह एव स्थातव्यं पतिव्रतयुजा सदा ॥14॥
                            </div>
                            <div class="anvaya">
                                अन्वयः- जीवता अजीवता अपि वा सहचारिण्याः अयं धर्मः, पतिव्रतयुजा पत्या सह एव सदा स्थातव्यम् ॥14॥
                            </div>
                            <div class="prati">
