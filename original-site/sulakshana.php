                            </div>
                            <div class="prati">
                                तात्पर्यम्- तब पिता के उस कन्या की माता शुभव्रता भी उस कन्याको छोडकर पतिके पीछे चलीगई याने सती धर्मसे आपही अग्निमे पैठकर जलगई ॥१३॥
                            </div>
                        </div>
                        
                        
                        <div class="total">
                            <div class="moolam">
