२९ - विश्वामित्रेण श्रीरामं प्रति सिद्धाश्रमसम्बन्धि पूर्ववृत्तवर्णनं ताभ्यां राघवाभ्यां सह स्वाश्रममुपेत्य विश्वामित्रस्य तत्रत्यैर्मुनिभिः पूजनम्
३० - श्रीरामकर्तृकं विश्वामित्रयज्ञस्य संरक्षणं राक्षसानां संहरणं च
