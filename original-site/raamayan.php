२१ - विश्वामित्रस्य सरोषं वचनमाकर्ण्य वसिष्ठेन राज्ञः प्रबोधनम्
२२ - राज्ञा स्वस्त्ययनपूर्वकं रामलक्ष्मणयोर्मुनिना सह प्रस्थापनं मार्गे तयोर्विश्वामित्राद् बलातिबलाख्यविद्ययोः प्राप्तिश्च
२३ - मुनिना सह श्रीरामलक्ष्मणयोः सरयूगङ्गासङ्गमसमीपे पुण्याश्रमे नक्तं विश्रामः
२४ - वारिणो भिद्यमानस्य किमयं तुमुलो ध्वनिरिति नौकागतस्य रामस्य प्रश्नं श्रुत्वा मुनिना तस्योत्तरदानं मलदकरूषताटकावनानां परिचयं दत्त्वा ताटकावधार्थं श्रीरामस्य प्रेरणं च
२५ - श्रीरामेणानुयुक्तेन विश्वामित्रेण ताटकाया जन्मविवाहशापादिप्रसङ्गं श्रावयित्वा तस्य ताटकावधाय प्रेरणम्
