४४ - भगीरथं प्रशस्य ब्रह्मणा तस्मै गङ्गाजलेन पितृतर्पणं कर्तुमनुज्ञादानं तत्सर्वं कृत्वा भगीरथस्य स्वपुरे गमनं गङ्गावतरणोपाख्यानस्य महिमा च
