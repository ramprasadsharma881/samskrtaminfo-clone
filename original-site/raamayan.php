३५ - शोणभद्रमुत्तीर्य विश्वामित्रप्रभृतीनां गङ्गातटं गत्वा तत्र रात्रौ वासः श्रीरामानुयुक्तेन विश्वामित्रेण तस्मै गङ्गोत्पत्तिकथाश्रावणम्
