१३ - राज्ञो वसिष्ठं प्रति यज्ञसमारम्भायानुरोधस्तेन तदर्थं सेवकानां नियुक्ति राज्ञामामन्त्रणाय तस्य सुमन्त्रं
प्रत्यादेशः समागतनरेशानां सत्कारः सपत्नीकेन राज्ञा यज्ञदीक्षाया ग्रहणं च
