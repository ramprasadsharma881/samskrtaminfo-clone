प्राजापत्यपुरुषेण पायसस्यार्पणं तद्भुक्त्वा राज्ञीनां गर्भधारणम्
१७ - ब्रह्मणः प्रेरणया देवादिभिर्विभिन्नवानरयूथपतीनामुत्पादनम्
